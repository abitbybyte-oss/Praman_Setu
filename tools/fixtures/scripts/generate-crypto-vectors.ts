import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { hexToBytes, bytesToHex } from "@noble/hashes/utils.js";
import {
  buildGenesisRecord,
  canonicalizeRecord,
  deviceIdFromPublicKey,
  keyIdFromPublicKey,
  publicKeyFromPrivateKey,
  publicKeyToJwk,
  sealRecord,
} from "@fdtc/evidence-core";

/** Regenerates tools/fixtures/crypto/es256-vectors.json.
 *
 * ARCHITECTURE §7.5: "Android/Java APIs emit DER, so any future native signer
 * must convert. A shared test vector guards this." ECDSA here is deterministic
 * (RFC 6979), so the signature bytes are reproducible and can be pinned — any
 * change to canonicalisation, hashing or signature encoding breaks the test.
 *
 * The key below is a published test key. It never signs real evidence. */

const PRIVATE_KEY_HEX = "0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20";

const privateKey = hexToBytes(PRIVATE_KEY_HEX);
const publicKey = publicKeyFromPrivateKey(privateKey);
const keyId = keyIdFromPublicKey(publicKey);

const genesis = buildGenesisRecord({
  publicKey,
  recordId: "0192a5c4-7e1b-7c3a-9f10-2b6d8e4f1a77",
  createdAt: "2026-09-22T10:00:00.000Z",
  appVersion: "0.1.0",
  platform: "fixture",
});

const spike = {
  schema: "fdtc.spike/1",
  record_type: "TEST",
  record_id: "0192a5c4-8f2c-7d4b-ae21-3c7e9f5a2b88",
  device_id: deviceIdFromPublicKey(publicKey),
  key_id: keyId,
  seq: 1,
  prev_hash: sealRecord(genesis, privateKey, keyId).record_hash,
  created_at: "2026-09-22T10:14:03.221Z",
  simulated: true,
  source: "FIXTURE",
  evidence_image: {
    n: 1,
    sha256: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
    mime: "image/jpeg",
    bytes: 0,
  },
};

const vectors = [genesis, spike].map((record) => {
  const envelope = sealRecord(record as Record<string, unknown>, privateKey, keyId);
  return {
    name: record.record_type === "GENESIS" ? "genesis" : "spike-test",
    jcs: canonicalizeRecord(record),
    record_hash: envelope.record_hash,
    signature_b64url: envelope.signature.value,
    envelope,
  };
});

const output = {
  note: "Generated by tools/fixtures/scripts/generate-crypto-vectors.ts. Do not hand-edit.",
  algorithm: "ES256 (ECDSA P-256 over SHA-256), 64-byte r||s, base64url",
  canonicalisation: "RFC 8785 JCS, UTF-8",
  private_key_hex: PRIVATE_KEY_HEX,
  public_key_hex: bytesToHex(publicKey),
  public_key_jwk: publicKeyToJwk(publicKey),
  key_id: keyId,
  device_id: deviceIdFromPublicKey(publicKey),
  vectors,
};

const outPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../crypto/es256-vectors.json"
);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(output, null, 2) + "\n");

console.log(`Wrote ${vectors.length} vectors to ${outPath}`);
for (const vector of vectors) {
  console.log(`  ${vector.name.padEnd(12)} ${vector.record_hash}`);
}
