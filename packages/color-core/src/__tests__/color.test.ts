describe("CIEDE2000", () => {
  it.each(SHARMA.map((p, i) => [i + 1, ...p] as const))("Sharma pair %i", (_n, a, b, expected) => {
    expect(deltaE00(a, b)).toBeCloseTo(expected, 4);
    expect(deltaE00(b, a)).toBeCloseTo(expected, 4); // symmetric
  });

  it("is zero for identical colours", () => {
    expect(deltaE00([55, -12, 30], [55, -12, 30])).toBe(0);
  });
});

describe("colour conversions", () => {
  it("maps sRGB white and black to L* 100 and 0", () => {
    const white = srgb8ToLab([255, 255, 255]);
    expect(white[0]).toBeCloseTo(100, 2);
    expect(Math.abs(white[1])).toBeLessThan(0.01);
    expect(Math.abs(white[2])).toBeLessThan(0.01);
    expect(srgb8ToLab([0, 0, 0])[0]).toBeCloseTo(0, 6);
  });

  it("matches a known sRGB red", () => {
    const [L, a, b] = srgb8ToLab([255, 0, 0]);
    expect(L).toBeCloseTo(53.24, 1);
    expect(a).toBeCloseTo(80.09, 1);
    expect(b).toBeCloseTo(67.2, 1);
  });

  it("round-trips sRGB -> Lab -> sRGB within 0.01", () => {
    for (let r = 0; r <= 255; r += 51)
      for (let g = 0; g <= 255; g += 51)
        for (let b = 0; b <= 255; b += 51) {
          const back = labToSrgb8(srgb8ToLab([r, g, b]));
          expect(Math.abs(back[0] - r)).toBeLessThan(0.01);
          expect(Math.abs(back[1] - g)).toBeLessThan(0.01);
          expect(Math.abs(back[2] - b)).toBeLessThan(0.01);
        }
  });

  it("round-trips Lab -> linear -> Lab for the card references", () => {
    for (const lab of [[95, -0.5, 2], [44, 60, 38], [34, 14, -48]] as Lab[]) {
      expect(deltaE00(linearToLab(labToLinear(lab)), lab)).toBeLessThan(1e-3);
    }
  });
});
